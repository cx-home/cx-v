// diagram_vector_golden_test.v — the WAVE-2 DR-8 bit-for-bit gate
// (#758, RULED 2026-08-20; ledger/rulings_2026_08_20_diagram_renderer.md).
//
// The corpus under vcx/tests/testdata/diagram_vector_golden/ was
// captured from the UNMODIFIED V renderer BEFORE the wave-2 cutover.
// It pins the DETERMINISTIC halves of the SVG/PNG path — the DOT text,
// both dot-less envelopes, and both metadata splices over FIXED inputs
// — so the CX port is byte-checkable without graphviz. graphviz's own
// output is version- and font-dependent and is therefore NOT goldened;
// the live end-to-end hop is gate 9's job.
//
// This lane is hermetic: it never spawns `dot` and needs no
// capability. Regenerating the corpus is golden movement — forbidden
// except under a DR-8 mini-ruling recorded in the ledger first.

